TARGET = 500   # 目标条数


def render(template, rng):
    """把一条模板渲染成一条训练数据：采样变量 → 计算派生值 → 填充占位符。"""
    values = {f: rng.choice(VARIABLES[f]) for f in template["fields"]}
    for key, fn in template.get("calc", {}).items():
        values[key] = fn(values)
    return {
        "instruction": template["instruction"].format(**values),
        "input": "",
        "output": template["output"].format(**values),
    }


def main():
    rng = random.Random(20240908)   # 固定种子，保证可复现
    data = []

    # ---- 可选：读手工 seed 文件（存在则先放入，再用模板补足到 TARGET）----
    # seed.json 格式：与 data.json 相同，是 [{instruction, input, output}, ...]
    seed_path = Path(__file__).parent / "seed.json"
    if seed_path.exists():
        seed = json.loads(seed_path.read_text(encoding="utf-8"))
        if isinstance(seed, dict):            # 兼容 {"data": [...]} 这种包一层的情况
            seed = seed.get("data", [])
        data.extend(seed)
        print(f"已读取 seed.json：{len(seed)} 条手工数据")

    # ---- 用模板批量生成，直到凑满 TARGET 条 ----
    topics = Counter()
    while len(data) < TARGET:
        tpl = rng.choice(TEMPLATES)
        data.append(render(tpl, rng))
        topics[tpl["topic"]] += 1

    data = data[:TARGET]                      # seed 超过 500 时截断
    out_path = Path(__file__).parent / "data.json"
    out_path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding="utf-8")

    print(f"已生成 {len(data)} 条训练数据 → {out_path}")
    print("\n知识点分布（条数）：")
    for topic, cnt in topics.most_common():
        print(f"  {topic:<10} {cnt}")
    print("\n样例（第 1 条）：")
    print("  instruction:", data[0]["instruction"])
    print("  output:", data[0]["output"])


