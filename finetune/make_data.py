# Day 15：LoRA 微调 · 生成「合同领域问答」训练数据（alpaca 格式）
# 目标：用内置的 20 条模板 + 变量池，批量生成 500 条训练数据，输出 data.json
# 依赖：无（只用 Python 标准库 random / json / pathlib / collections）
# 运行：py make_data.py
# 产出：同目录下 data.json，每条形如 {"instruction": "...", "input": "", "output": "..."}
#
# 设计思路（面试能聊）：
#   1) LoRA 微调本质是「补数据」，数据质量 > 数量。所以这里用「模板 + 变量替换」做增强，
#      同一知识点换公司名/人名/金额/年限，让模型学会「规则」而不是背「原题」。
#   2) instruction 放任务描述，output 放标准答案；input 留空（当任务是「给定一段背景材料
#      再回答」时，才把材料填进 input）。LLaMA-Factory 的 alpaca 格式会自动拼接这三列。
#   3) 固定随机种子 random.Random(...)，保证每次运行生成的数据可复现，方便对比实验。

